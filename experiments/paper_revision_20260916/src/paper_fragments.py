SETUP = r"""
\subsection{Non-affine physical parameter benchmark}
\label{sec:nonaffine_setup}

The scalar and coupled benchmarks are affine in the physical coefficients.
A third benchmark is therefore added, in which the parameter enters the residual
non-affinely.
The saturation coefficient $\kappa$ is inverted in
\begin{equation}
u_t = D\,u_{xx} + \rho\,\frac{u}{1+\kappa u} + f(x,t),
\label{eq:saturation_system}
\end{equation}
with $D=0.01$ and $\rho=1$ fixed.
The truth is $\kappa^\star=1.2$, the initial value is $0.8$, and the parameter is
inverted in the log coordinate $\lambda=\log\kappa$.
The coefficient therefore changes the reaction shape across state values.
The coefficient enters the model beyond the affine family.

A manufactured solution supplies the data.
The domain is $[0,1]\times[0,0.4]$ with periodic boundaries.
The source $f$ is generated once from the true $\kappa$ and then held fixed.
A positive output transform keeps $1+\kappa u$ away from zero.
Ninety-six PDE points, one hundred and twenty-eight observation points, forty-eight
initial points and forty-eight boundary times are used.
Block weights are $5$, $10$, $10$ and $2$.
Two noise levels are applied to the observation residuals only, at $0$ and $0.02$.
Eight development fits and twenty-four held-out fits are planned.
Development and held-out data seeds are disjoint.

The non-affine contribution is measured directly.
At a fixed state, $r_{\kappa}=\rho u^{2}/(1+\kappa u)^{2}$ and
$r_{\kappa\kappa}=-2\rho u^{3}/(1+\kappa u)^{3}$.
In the log coordinate,
\begin{equation}
H_{\lambda\lambda}-G_{\lambda\lambda}-g_\lambda
= \kappa^{2}\sum_i \bar r_i\,\partial_{\kappa\kappa}\bar r_i .
\label{eq:nonaffine_identity}
\end{equation}
Both sides are reported, so the contribution from the log coordinate is separated from
the genuinely non-affine contribution.
"""

